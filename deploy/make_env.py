"""Create .env.prod for docker-compose.prod.yml with fresh, random secrets.

    python deploy/make_env.py --domain laundryconnect.duckdns.org     # the real server
    python deploy/make_env.py --local                                 # try it on this computer

Only needs Python 3 (standard library). Refuses to overwrite an existing
.env.prod so secrets – above all the backup key – are never lost by accident.
Copy POSTGRES_PASSWORD and BACKUP_ENCRYPTION_KEY into a password manager.
"""

import argparse
import base64
import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    where = parser.add_mutually_exclusive_group(required=True)
    where.add_argument("--domain", help="public domain, e.g. laundryconnect.duckdns.org")
    where.add_argument("--local", action="store_true", help="plain http on this computer")
    parser.add_argument("--port", type=int, default=8088, help="local http port (with --local)")
    parser.add_argument("--contact", default="", help="contact e-mail for the address-search service")
    args = parser.parse_args()

    target = ROOT / ".env.prod"
    if target.exists():
        print(f"{target} already exists – not overwriting it (it holds your secrets).")
        return 1

    if args.local:
        site, http_port, https_port = ":80", args.port, args.port + 1
        public = f"http://localhost:{args.port}"
    else:
        site, http_port, https_port = args.domain, 80, 443
        public = f"https://{args.domain}"

    agent = f"LaundryConnect/1.0 ({args.contact})" if args.contact else "LaundryConnect/1.0"
    values = {
        "# Generated by deploy/make_env.py – keep this file private": None,
        "SITE_ADDRESS": site,
        "HTTP_PORT": http_port,
        "HTTPS_PORT": https_port,
        "PUBLIC_APP_URL": public,
        "PUBLIC_API_URL": public,
        "CORS_ORIGINS": public,
        "POSTGRES_PASSWORD": secrets.token_urlsafe(24),
        "JWT_SECRET_KEY": secrets.token_urlsafe(48),
        # Fernet key: 32 random bytes, url-safe base64
        "BACKUP_ENCRYPTION_KEY": base64.urlsafe_b64encode(os.urandom(32)).decode(),
        "GEOCODER_USER_AGENT": agent,
        "# Payments: sandbox until PayFast is set up (docs/PAYMENTS.md)": None,
        "PAYMENT_PROVIDER": "sandbox",
        "PAYFAST_SANDBOX": "true",
        "PAYFAST_MERCHANT_ID": "",
        "PAYFAST_MERCHANT_KEY": "",
        "PAYFAST_PASSPHRASE": "",
        "# SMS: log until BulkSMS is set up (docs/SMS.md)": None,
        "SMS_PROVIDER": "log",
        "BULKSMS_TOKEN_ID": "",
        "BULKSMS_TOKEN_SECRET": "",
    }
    lines = [k if v is None else f"{k}={v}" for k, v in values.items()]
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "backups").mkdir(exist_ok=True)
    print(f"Created {target} for {public}")
    print("IMPORTANT: save POSTGRES_PASSWORD and BACKUP_ENCRYPTION_KEY in a password manager.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
